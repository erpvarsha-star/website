#!/usr/bin/env node
/*
 * build-embed-modules.js  (W5 prep)
 *
 * Generates, inside the Velo repo (default /home/user/vflwebsite):
 *   src/backend/embeds/<key>.js      one module per corrected embed (exports `html`)
 *   src/backend/embeds/index.js      static key -> html table (Velo needs static imports)
 *   src/public/corrections-rules.js  text/hide rules ported from corrections/embed-layer*.js
 *   src/pages/<Page>.<id>.js         W5 header + onReady block (idempotent, markers W5-BEGIN/W5-END)
 *
 * Only embeds marked with >=1 change in embeds/INDEX.md are included.
 * Embeds sharing one iframe src (about-1-1 x3) share one key (the first).
 *
 * Usage: node scripts/build-embed-modules.js [veloRepoDir]
 */
const fs = require('fs');
const path = require('path');

const WEBSITE = path.resolve(__dirname, '..');
const VELO = path.resolve(process.argv[2] || '/home/user/vflwebsite');

// slug -> Velo pageId (verified against live rawHtml "Container<pageId>inlineContent", 22 Nov 2026)
const PAGE_IDS = {
  'forging-manufacturer-pune': 'lgtlq',
  'forging-manufacturer-india': 'q1c5f',
  'forging-company-maharashtra': 'n1h72',
  'suspension-components': 'bz4vb',
  'forged-components-railways': 'l2sru',
  'radius-rod-assemblies': 'zwiw1',
  'torque-rod-assemblies': 'wu1va',
  'v-link-assemblies': 'mfcwu',
  'forged-components-ev': 'jq1y2',
  'about-1': 'l95rc',
  'oil-and-gas': 'xr827',
  'forging-vs-casting': 'cyo3l',
  'about-1-1': 'slfrq',
  'forged-machined-components-vf': 'owlox',
  'buying-forgings-from-india': 'ztibo',
  'heat-treatment-metallurgy': 'nwsbm',
  'forging-company-aurangabad': 'dpizt',
};

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

// ---- 1. parse INDEX.md -------------------------------------------------
const rows = [];
for (const line of fs.readFileSync(path.join(WEBSITE, 'embeds/INDEX.md'), 'utf8').split('\n')) {
  const m = /^\| \/([a-z0-9-]+) \| (\d+) \| (https:\/\/\S+?72f2bf_([0-9a-f]{32})\.html) \| (\d+) \|/.exec(line);
  if (m) rows.push({ slug: m[1], n: +m[2], hash: '72f2bf_' + m[4], changes: +m[5] });
}
const changed = rows.filter((r) => r.changes > 0);

// ---- 2. embed modules --------------------------------------------------
const embedsDir = path.join(VELO, 'src/backend/embeds');
fs.rmSync(embedsDir, { recursive: true, force: true });
const keyByHash = {};
const pageMaps = {}; // slug -> { hash: key }
const keys = [];
for (const r of changed) {
  let key = keyByHash[r.hash];
  if (!key) {
    key = `${r.slug}__${r.n}`;
    const src = path.join(WEBSITE, 'embeds/corrected', `${key}.html`);
    const html = fs.readFileSync(src, 'utf8');
    write(
      path.join(embedsDir, `${key}.js`),
      `// GENERATED by scripts/build-embed-modules.js from embeds/corrected/${key}.html. Do not edit.\n` +
        `// Replaces filesusr embed ${r.hash}\n` +
        `export const html = ${JSON.stringify(html)};\n`
    );
    keyByHash[r.hash] = key;
    keys.push({ key, hash: r.hash, bytes: Buffer.byteLength(html) });
  }
  (pageMaps[r.slug] = pageMaps[r.slug] || {})[r.hash] = key;
}
const ident = (k) => 'e_' + k.replace(/[^a-z0-9]/gi, '_');
write(
  path.join(embedsDir, 'index.js'),
  '// GENERATED by scripts/build-embed-modules.js. Do not edit.\n' +
    keys.map((k) => `import { html as ${ident(k.key)} } from './${k.key}.js';`).join('\n') +
    '\n\nexport const EMBEDS = {\n' +
    keys.map((k) => `  ${JSON.stringify(k.key)}: ${ident(k.key)},`).join('\n') +
    '\n};\n'
);

// ---- 3. corrections rules ----------------------------------------------
function loadLayer(file) {
  const s = fs.readFileSync(path.join(WEBSITE, 'corrections', file), 'utf8');
  const a = s.indexOf('var T=');
  const b = s.indexOf('var SK=');
  // eslint-disable-next-line no-new-func
  return new Function(s.slice(a, b) + ';return {T:T,H:typeof H!=="undefined"?H:[]};')();
}
const L1 = loadLayer('embed-layer.js');
const L2 = loadLayer('embed-layer-2.js');
const T = L1.T.concat(L2.T);
const H = L1.H.concat(L2.H);
const lit = (v) => (v instanceof RegExp ? String(v) : JSON.stringify(v));
const fmt = (arr) => '  [' + arr.map(lit).join(', ') + '],';
write(
  path.join(VELO, 'src/public/corrections-rules.js'),
  '// GENERATED by scripts/build-embed-modules.js from corrections/embed-layer.js and embed-layer-2.js. Do not edit.\n' +
    '// TEXT_RULES: [regex, replacement, optional page-path regex source]\n' +
    '// HIDE_RULES: [phrase, optional page-path regex source, 1 = keep first occurrence]\n' +
    '// HREF_RULES: [regex, replacement]\n' +
    'export const TEXT_RULES = [\n' + T.map(fmt).join('\n') + '\n];\n\n' +
    'export const HIDE_RULES = [\n' + H.map(fmt).join('\n') + '\n];\n\n' +
    'export const HREF_RULES = [\n  [/mailto:marketing@varshaforging\\.com/gi, "mailto:marketing@varshaforgings.com"],\n];\n'
);

// ---- 4. page wiring -----------------------------------------------------
const pagesDir = path.join(VELO, 'src/pages');
const HEADER_RE = /\/\/ W5-BEGIN header[\s\S]*?\/\/ W5-END header\n/;
const BODY_RE = /[ \t]*\/\/ W5-BEGIN body[\s\S]*?\/\/ W5-END body\n/;
const idToSlug = Object.fromEntries(Object.entries(PAGE_IDS).map(([s, id]) => [id, s]));
let wired = 0;
const pageReport = [];
for (const f of fs.readdirSync(pagesDir).filter((x) => x.endsWith('.js'))) {
  const pid = (/\.([a-z0-9]{5})\.js$/.exec(f) || [])[1];
  const map = (pid && idToSlug[pid] && pageMaps[idToSlug[pid]]) || null;
  let src = fs.readFileSync(path.join(pagesDir, f), 'utf8');
  src = src.replace(HEADER_RE, '').replace(BODY_RE, '');
  const header =
    '// W5-BEGIN header (generated by scripts/build-embed-modules.js)\n' +
    "import { applyTextCorrections } from 'public/corrections.js';\n" +
    (map ? "import { swapEmbeds } from 'public/embedSwap.js';\n" : '') +
    (map ? `const W5_EMBEDS = ${JSON.stringify(map, null, 2)};\n` : '') +
    '// W5-END header\n';
  const body =
    '    // W5-BEGIN body\n' +
    (map ? '    let w5Swapped = [];\n    try { w5Swapped = swapEmbeds($w, W5_EMBEDS); } catch (e) { /* never break rendering */ }\n' : '') +
    '    try { applyTextCorrections($w); } catch (e) { /* never break rendering */ }\n' +
    '    // W5-END body\n';
  // header goes after the leading comment lines
  const lines = src.split('\n');
  let i = 0;
  while (i < lines.length && /^\s*(\/\/.*)?$/.test(lines[i]) && !/^\$w\.onReady/.test(lines[i])) i++;
  // keep trailing blank lines of the comment block together
  // Idempotence: a previous run leaves its separator blank lines behind. Collapse the blank run just
  // before the header to exactly one, which is what the first run on a pristine file produces.
  let j = i;
  while (j > 0 && lines[j - 1] === '') j--;
  const sep = j > 0 ? [''] : [];
  lines.splice(j, i - j, ...sep, header.replace(/\n$/, ''), '');
  src = lines.join('\n');
  const re = /^\$w\.onReady\(function \(\) \{\n/m;
  if (!re.test(src)) throw new Error('no onReady in ' + f);
  src = src.replace(re, (m) => m + body);
  fs.writeFileSync(path.join(pagesDir, f), src);
  wired++;
  pageReport.push({ file: f, pid, slug: idToSlug[pid] || null, embeds: map ? Object.keys(map).length : 0 });
}

console.log(
  JSON.stringify(
    {
      indexRows: rows.length,
      rowsWithChanges: changed.length,
      uniqueEmbedModules: keys.length,
      textRules: T.length,
      hideRules: H.length,
      pageFilesPatched: wired,
      pagesWithEmbedSwap: pageReport.filter((p) => p.embeds).length,
      largestModuleBytes: Math.max(...keys.map((k) => k.bytes)),
      totalModuleBytes: keys.reduce((a, k) => a + k.bytes, 0),
    },
    null,
    2
  )
);
if (process.env.VERBOSE) console.log(JSON.stringify({ keys, pageReport }, null, 1));
